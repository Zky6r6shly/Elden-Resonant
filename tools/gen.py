#!/usr/bin/env python3
"""Generate mod/src/generated.rs from the sheets: one Rust struct value per row.

Refuses to run unless the preflight is clean.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from preflight import ROOT, load, preflight  # noqa: E402


def s(v):
    return json.dumps(v, ensure_ascii=False)


def main():
    sheets = load()
    problems = preflight(sheets)
    if problems:
        print("preflight not clean; run tools/preflight.py", file=sys.stderr)
        sys.exit(1)
    fin = {r["key"]: r for r in sheets["finishers"]["rows"]}
    cues = [r["key"] for r in sheets["cues"]["rows"]]
    out = ["// @generated by tools/gen.py from sheets/*.json. Edit the sheets, not this file.", ""]
    out.append("#![allow(dead_code)]")
    out.append("")
    out.append("pub struct Form { pub key: &'static str, pub name: &'static str, pub weapon_id: u32, pub class_slot: &'static str, pub finisher: usize, pub attack_physics: u16, pub weight: f32, pub info: &'static str, pub caption: &'static str, pub cue: usize }")
    out.append("pub struct Finisher { pub key: &'static str, pub name: &'static str, pub sword_arts_id: i32, pub description: &'static str, pub cue: usize }")
    out.append("pub struct Ability { pub key: &'static str, pub name: &'static str, pub goods_id: u32, pub fp_cost: i16, pub class_item_slot: u8, pub info: &'static str, pub caption: &'static str, pub cue: usize }")
    out.append("pub struct StartClass { pub chara_init_id: u32, pub replaces_class_text: &'static str, pub class_name: &'static str, pub soul_lv: i16, pub vit: u8, pub mind: u8, pub end: u8, pub str_: u8, pub dex: u8, pub int: u8, pub fai: u8, pub arc: u8 }")
    out.append("pub struct Cue { pub key: &'static str, pub keywords: &'static [&'static str], pub volume: f32 }")
    out.append("")
    fkeys = [r["key"] for r in sheets["finishers"]["rows"]]
    out.append("pub const FINISHERS: &[Finisher] = &[")
    for r in sheets["finishers"]["rows"]:
        out.append(f"    Finisher {{ key: {s(r['key'])}, name: {s(r['name'])}, sword_arts_id: {r['erSwordArtsId']}, description: {s(r['description'])}, cue: {cues.index(r['crCue'])} }},")
    out.append("];")
    out.append("pub const FORMS: &[Form] = &[")
    for r in sheets["forms"]["rows"]:
        out.append(f"    Form {{ key: {s(r['key'])}, name: {s(r['name'])}, weapon_id: {r['erBaseWeaponId']}, class_slot: {s(r['classSlot'])}, finisher: {fkeys.index(r['finisher'])}, attack_physics: {r['attackPhysics']}, weight: {float(r['weight'])}, info: {s(r['info'])}, caption: {s(r['caption'])}, cue: {cues.index(r['crCue'])} }},")
    out.append("];")
    out.append("pub const ABILITIES: &[Ability] = &[")
    for r in sheets["abilities"]["rows"]:
        out.append(f"    Ability {{ key: {s(r['key'])}, name: {s(r['name'])}, goods_id: {r['erGoodsId']}, fp_cost: {r['fpCost']}, class_item_slot: {r['classItemSlot']}, info: {s(r['info'])}, caption: {s(r['caption'])}, cue: {cues.index(r['crCue'])} }},")
    out.append("];")
    c = sheets["starting_class"]["rows"][0]
    out.append(f"pub const START_CLASS: StartClass = StartClass {{ chara_init_id: {c['erCharaInitId']}, replaces_class_text: {s(c['replacesClassText'])}, class_name: {s(c['className'])}, soul_lv: {c['soulLv']}, vit: {c['vit']}, mind: {c['mind']}, end: {c['end']}, str_: {c['str']}, dex: {c['dex']}, int: {c['int']}, fai: {c['fai']}, arc: {c['arc']} }};")
    out.append("pub const CUES: &[Cue] = &[")
    for r in sheets["cues"]["rows"]:
        kw = ", ".join(s(k) for k in r["keywords"])
        out.append(f"    Cue {{ key: {s(r['key'])}, keywords: &[{kw}], volume: {float(r['volume'])} }},")
    out.append("];")
    out.append(f"pub const CUE_ARRIVAL: usize = {cues.index('arrival')};")
    dest = ROOT / "mod" / "src" / "generated.rs"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dest.relative_to(ROOT)}: {len(sheets['forms']['rows'])} forms, {len(fin)} finishers, "
          f"{len(sheets['abilities']['rows'])} abilities, {len(cues)} cues")


if __name__ == "__main__":
    main()
